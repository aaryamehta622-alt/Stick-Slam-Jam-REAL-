export function designFor(ability:MoveVFX['ability'], element?:number, category='brawler'):EffectDesign {
  if(ability==='heavy')return d(category==='heavy'?'slam':category==='mage'?'nova':category==='ranged'?'rail':'cut','#b6d6ff','#ffffff',1.7,8,'charged-release');
  if(ability==='light'||ability==='dash')return d(ability==='dash'?'dash':'cut','#a4d6ff','#ffffff',0.7,2,'basic');
  const design=ABILITY_DESIGNS[ability];
  if(ability.startsWith('element') && ability!=='elementalNova' && element!==undefined) {
    const color=['#ff793d','#64e1ff','#ffe84c'][element],accent=['#fff2a6','#f1ffff','#fffedb'][element];
    const form=ability==='elementUlt'?(['meteor','frost','chain'] as const)[element]:ability==='elementCombo'?(['dragon','frost','chain'] as const)[element]:ability==='elementMobility'?(element===2?'blink':'dash'):design.form;
    return {...design,color,accent,form};
  }
  return design;
}
